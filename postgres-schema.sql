DROP TRIGGER IF EXISTS order_items_popularity_delete ON order_items;
CREATE TRIGGER order_items_popularity_insert AFTER INSERT ON order_items
FOR EACH ROW EXECUTE FUNCTION maintain_product_popularity();
CREATE TRIGGER order_items_popularity_update AFTER UPDATE OF product_id, quantity ON order_items
FOR EACH ROW EXECUTE FUNCTION maintain_product_popularity();
CREATE TRIGGER order_items_popularity_delete AFTER DELETE ON order_items
FOR EACH ROW EXECUTE FUNCTION maintain_product_popularity();
