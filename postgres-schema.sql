CREATE OR REPLACE FUNCTION maintain_product_popularity() RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.product_id IS NOT NULL THEN
      UPDATE products SET popularity = popularity + NEW.quantity WHERE id = NEW.product_id;
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    IF OLD.product_id IS NOT NULL THEN
      UPDATE products SET popularity = GREATEST(0, popularity - OLD.quantity) WHERE id = OLD.product_id;
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.product_id IS DISTINCT FROM NEW.product_id OR OLD.quantity IS DISTINCT FROM NEW.quantity THEN
    IF OLD.product_id IS NOT NULL THEN
      UPDATE products SET popularity = GREATEST(0, popularity - OLD.quantity) WHERE id = OLD.product_id;
    END IF;
    IF NEW.product_id IS NOT NULL THEN
      UPDATE products SET popularity = popularity + NEW.quantity WHERE id = NEW.product_id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS order_items_popularity_insert ON order_items;
